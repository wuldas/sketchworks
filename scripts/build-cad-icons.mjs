import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const svgDir = path.join(root, "src/icons/svg");
const dataFile = path.join(root, "src/icons/cadIconData.ts");

const iconNames = [
  "parallel",
  "tangent",
  "perpendicular",
  "vertical",
  "horizontal",
  "chamfer",
  "mirror",
  "offset",
  "arc-3-point",
  "arc-center",
  "fillet",
  "bezier",
  "slot",
];

const fillTokens = new Map([
  ["#040000", "ink"],
  ["#515151", "strong"],
  ["#676768", "muted"],
  ["#A6A6A6", "subtle"],
  ["#20A2DD", "blue"],
  ["#F39835", "orange"],
  ["#DCDDDD", "line"],
]);

const pathAttributes = new Set([
  "d",
  "fill",
  "stroke",
  "stroke-width",
  "stroke-linecap",
  "stroke-linejoin",
  "stroke-dasharray",
]);

function parseSvg(name, source) {
  const svg = source.match(
    /<svg\b[^>]*\bviewBox="([^"]+)"[^>]*>([\s\S]*?)<\/svg>/,
  );
  if (!svg) throw new Error(`${name}.svg: missing <svg viewBox="...">`);

  const paths = [];
  const strokes = [];

  for (const [, attributes] of svg[2].matchAll(/<path\b([^>]*)\/>/g)) {
    const attr = (key) =>
      attributes.match(new RegExp(`(?:^|\\s)${key}="([^"]*)"`))?.[1];
    const d = attr("d");
    if (!d) throw new Error(`${name}.svg: path without d`);

    const unknown = [...attributes.matchAll(/([\w-]+)="([^"]*)"/g)]
      .map(([, key]) => key)
      .filter((key) => !pathAttributes.has(key));
    if (unknown.length) {
      throw new Error(
        `${name}.svg: unsupported path attributes: ${unknown.join(", ")}`,
      );
    }

    const fill = attr("fill");
    const stroke = attr("stroke");

    if (stroke) {
      if (stroke !== "currentColor") {
        throw new Error(`${name}.svg: stroke must be currentColor`);
      }
      if (fill && fill !== "none") {
        throw new Error(`${name}.svg: mixed fill and stroke is not supported`);
      }
      for (const key of ["stroke-linecap", "stroke-linejoin"]) {
        const value = attr(key);
        if (value && value !== "round") {
          throw new Error(`${name}.svg: ${key} must be round`);
        }
      }
      const width = Number(attr("stroke-width") ?? 1);
      if (!Number.isFinite(width) || width <= 0) {
        throw new Error(`${name}.svg: invalid stroke-width`);
      }
      const dash = attr("stroke-dasharray");
      strokes.push({ d, width, ...(dash ? { dash } : {}) });
      continue;
    }

    if (fill === "none") {
      throw new Error(`${name}.svg: path has neither fill nor stroke`);
    }
    const token = fill ? fillTokens.get(fill.toUpperCase()) : "ink";
    if (!token) throw new Error(`${name}.svg: unmapped fill ${fill}`);
    paths.push({ d, fill: token });
  }

  if (!paths.length && !strokes.length) {
    throw new Error(`${name}.svg: no paths`);
  }
  return { viewBox: svg[1], paths, strokes };
}

const icons = [];
for (const name of iconNames) {
  const source = await readFile(path.join(svgDir, `${name}.svg`), "utf8");
  icons.push([name, parseSvg(name, source)]);
}

const body = icons
  .map(([name, icon]) => {
    const sections = [];
    if (icon.paths.length) {
      sections.push(`    paths: [
${icon.paths
  .map(
    (iconPath) => `      {
        d: ${JSON.stringify(iconPath.d)},
        fill: ${JSON.stringify(iconPath.fill)},
      },`,
  )
  .join("\n")}
    ],`);
    }
    if (icon.strokes.length) {
      sections.push(`    strokes: [
${icon.strokes
  .map(
    (stroke) => `      {
        d: ${JSON.stringify(stroke.d)},
        width: ${stroke.width},${stroke.dash ? `\n        dash: ${JSON.stringify(stroke.dash)},` : ""}
      },`,
  )
  .join("\n")}
    ],`);
    }
    return `  /** ${name} */
  ${JSON.stringify(name)}: icon({
    viewBox: ${JSON.stringify(icon.viewBox)},
${sections.join("\n")}
  }),`;
  })
  .join("\n");

const output = `// Generated by scripts/build-cad-icons.mjs from src/icons/svg/*.svg.
// Do not edit this file by hand; edit the SVG source and run \`pnpm icons:build\`.
// SVG fills are mapped to the theme tokens defined in cadIcons.css.
// Stroke-only icons use currentColor and adapt to the surrounding text color.

export type CadIconFill =
  | "ink"
  | "strong"
  | "muted"
  | "subtle"
  | "blue"
  | "orange"
  | "line";

export type CadIconPath = {
  d: string;
  fill: CadIconFill;
};

export type CadIconStroke = {
  d: string;
  width: number;
  dash?: string;
};

export type CadIconDefinition = {
  viewBox: string;
  paths?: CadIconPath[];
  strokes?: CadIconStroke[];
};

function icon<const T extends CadIconDefinition>(definition: T): T {
  return definition;
}

export const cadIconData = {
${body}
};

export type CadIconName = keyof typeof cadIconData;
`;

await writeFile(dataFile, output);
console.log(`Generated ${icons.length} icons from src/icons/svg`);
